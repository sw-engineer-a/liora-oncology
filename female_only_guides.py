def _row(folder, condition, sid, symptom, weight, urgency, t1, t2, t3):
    return {
        "folder": folder,
        "condition": condition,
        "symptom_id": sid,
        "symptom": symptom,
        "weight": str(weight),
        "urgency": urgency,
        "treatment_1": t1,
        "treatment_2": t2,
        "treatment_3": t3,
    }


def _pack(folder, condition, items):
    return [_row(folder, condition, *item) for item in items]


